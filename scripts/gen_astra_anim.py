#!/usr/bin/env python3
"""Generate 12-frame counter-clockwise rotating 4-arm galaxy animation (A8)
for icons.c — the Astra radar-row icon.

Style matches the radar icon family: 48x48 monochrome, integer pixel
placement only (crisp on RLCD). Two thick main arms + two thin secondary
arms, solid core with dashed halo, star knots on the arms, 6 field stars.
One loop turns 180 deg CCW; the 4 arms' 90-deg symmetry makes the loop
seamless (frame[12] == frame[0]).

Outputs a marker-delimited block into icons.c and declarations into
icons.h (idempotent rewrite between markers).
"""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
ICONS_C = ROOT / "firmware" / "components" / "ui_app" / "icons.c"
ICONS_H = ROOT / "firmware" / "components" / "ui_app" / "icons.h"
SIZE = 48
FRAMES = 12
CX = CY = 23.5
TILT = 0.80          # y-flatten for the disk inclination
STEP_R = 0.55        # radius step along an arm
WIND = 0.16          # radians of twist per radius step
CCW = True           # counter-clockwise (Milky-Way-from-above convention)


def render(rot_deg: float):
    grid = [[0] * SIZE for _ in range(SIZE)]
    rot = math.radians(-rot_deg if CCW else rot_deg)

    def put(xf, yf):
        x, y = int(round(xf)), int(round(yf))
        if 0 <= x < SIZE and 0 <= y < SIZE:
            grid[y][x] = 255

    # core: solid disc r=4 + dashed halo to r=6
    for y in range(SIZE):
        for x in range(SIZE):
            d = math.hypot(x - CX, y - CY)
            if d <= 4:
                grid[y][x] = 255
            elif d <= 6 and (x + y) % 2 == 0:
                grid[y][x] = 255

    def arm(theta0: float, thick: bool):
        r = 5.0
        theta = theta0
        while r <= 20.0:
            a = theta + rot
            offs = (r, r + 0.8) if thick else (r,)
            for rr in offs:
                put(CX + rr * math.cos(a), CY + rr * math.sin(a) * TILT)
            theta += WIND
            r += STEP_R

    arm(0.0, True)
    arm(math.pi, True)
    arm(math.pi / 2, False)
    arm(3 * math.pi / 2, False)

    # star knots: 2 per arm (2x2 blocks)
    for t0 in (0.0, math.pi / 2, math.pi, 3 * math.pi / 2):
        for k in (1, 3):
            r = 7 + k * 4
            theta = t0 + (r - 5.0) / STEP_R * WIND
            a = theta + rot
            x = int(round(CX + r * math.cos(a)))
            y = int(round(CY + r * math.sin(a) * TILT))
            for dx, dy in ((0, 0), (1, 0), (0, 1), (1, 1)):
                if 0 <= x + dx < SIZE and 0 <= y + dy < SIZE:
                    grid[y + dy][x + dx] = 255

    for sx, sy in ((7, 9), (41, 10), (8, 39), (39, 41), (24, 4), (5, 24)):
        grid[sy][sx] = 255
    return grid


frames = [render(f * (180.0 / FRAMES)) for f in range(FRAMES)]

# seam check: frame at 180deg must equal frame 0 (90-deg arm symmetry + 180 loop)
g180 = render(180.0)
seam = sum(1 for y in range(SIZE) for x in range(SIZE)
           if (g180[y][x] > 0) != (frames[0][y][x] > 0))
ons = [sum(1 for y in range(SIZE) for x in range(SIZE) if frames[f][y][x]) for f in range(FRAMES)]
print("per-frame ON:", ons)
print(f"seam frame[0] vs frame@180deg: {seam} pixels differ")
assert seam == 0, "seam mismatch"


def emit_frame(idx, grid):
    arr = ",".join(str(v) for y in range(SIZE) for v in (grid[y][x] for x in range(SIZE)))
    return (f"static const uint8_t astra_anim_f{idx}_map[] = {{{arr}}};\n"
            f"const lv_image_dsc_t icon_astra_anim_f{idx} = {{\n"
            f"  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,\n"
            f"               .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE} }},\n"
            f"  .data_size = {SIZE*SIZE}, .data = astra_anim_f{idx}_map,\n}};\n")


block_lines = [
    "/* === BEGIN astra animation (generated by scripts/gen_astra_anim.py) === */",
    "",
]
for i, grid in enumerate(frames):
    block_lines.append(emit_frame(i, grid))
    block_lines.append("")
block_lines.append("const lv_image_dsc_t *icon_astra_anim[] = {"
                   + ", ".join(f"&icon_astra_anim_f{i}" for i in range(FRAMES)) + "};")
block_lines.append(f"const int icon_astra_anim_count = {FRAMES};")
block_lines.append("")
block_lines.append("/* === END astra animation === */")
block_lines.append("")
block = "\n".join(block_lines)

c_src = ICONS_C.read_text(encoding="utf-8", errors="replace")
import re
pat = re.compile(r"/\* === BEGIN astra animation.*?=== END astra animation === \*/\n?", re.DOTALL)
if pat.search(c_src):
    c_src = pat.sub(block.rstrip("\n"), c_src)
else:
    c_src = c_src.rstrip() + "\n\n" + block
ICONS_C.write_text(c_src, encoding="utf-8")

h_decl = (
    "/* astra (galaxy) animation frames (generated) */\n"
    "extern const lv_image_dsc_t *icon_astra_anim[];\n"
    "extern const int icon_astra_anim_count;\n"
)
h_src = ICONS_H.read_text(encoding="utf-8")
h_pat = re.compile(r"/\* astra \(galaxy\) animation frames.*?extern const int icon_astra_anim_count;\n", re.DOTALL)
if h_pat.search(h_src):
    h_src = h_pat.sub(h_decl, h_src)
else:
    h_src = h_src.rstrip() + "\n" + h_decl
ICONS_H.write_text(h_src, encoding="utf-8")

print(f"wrote {FRAMES} frames to icons.c / icons.h ({SIZE}x{SIZE} A8 each, {SIZE*SIZE} bytes/frame)")
